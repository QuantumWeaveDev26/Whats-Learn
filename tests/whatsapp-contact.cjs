const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = fs.readFileSync(path.join(process.cwd(), 'lib', 'contact.ts'), 'utf8');
assert.match(source, /whatsappContactNumber='919972965677'/, 'team support uses its own number');
assert.match(source, /whatsappLearningNumber='919187951536'/, 'learning uses the WhatsLearn account');
const ts=require('typescript');
const moduleResult={exports:{}};
new Function('exports',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText)(moduleResult.exports);
assert.equal(new URL(moduleResult.exports.whatsappChatUrl()).pathname,'/919972965677');
assert.equal(new URL(moduleResult.exports.whatsappLearningUrl()).pathname,'/919187951536');
assert.match(source, /https:\/\/wa\.me\//, 'contact link uses WhatsApp click-to-chat');
console.log('WhatsApp contact configuration passed');
